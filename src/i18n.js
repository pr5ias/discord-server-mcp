/** The texts that can be replaced per automation, with their English defaults. */
export const TEXT_KEYS = Object.keys(STRINGS.en);

/** Language code for a Discord locale such as "pt-BR" or "en-US". */
export function languageOf(locale) {
  const l = String(locale || "").toLowerCase();
  // Discord's only Portuguese locale is pt-BR, so servers set to Portuguese get Brazilian texts unless an
  // automation chooses "pt" (European Portuguese).
  if (l === "pt" || l === "pt-pt") return "pt";
  if (l.startsWith("pt")) return "pt-BR";
  if (l === "zh-cn" || l === "zh") return "zh-CN";
  // Other languages fall back to English; every text can still be replaced with `texts`.
  return STRINGS[l.split("-")[0]] && l.split("-")[0] !== "zh" ? l.split("-")[0] : "en";
}

/**
 * Text for key in lang ("auto" = the given locale), with {placeholders} filled and the automation's own
 * texts taking precedence.
 */
export function text(key, { lang = "auto", locale, texts, vars = {} } = {}) {
  const l = lang === "auto" || !lang ? languageOf(locale) : languageOf(lang);
  let out = texts?.[key] ?? STRINGS[l][key] ?? STRINGS.en[key] ?? key;
  for (const [k, v] of Object.entries(vars)) out = out.replaceAll(`{${k}}`, String(v ?? ""));
  return out;
}
